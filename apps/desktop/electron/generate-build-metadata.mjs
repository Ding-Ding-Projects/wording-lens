import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const packageData = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const configured = process.env.BUILD_UPDATED_AT;
let updatedAt = configured ?? "";
let source = configured ? "generated-from-build-environment" : "generated-from-commit-metadata";

if (!updatedAt) {
  try {
    updatedAt = execFileSync("git", ["log", "-1", "--format=%cI", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  } catch {
    updatedAt = "";
    source = "unavailable";
  }
}

if (Number.isNaN(Date.parse(updatedAt))) {
  updatedAt = "";
  source = "unavailable";
}

const content = `// Generated by npm run generate:build-metadata. Do not edit by hand.\nexport const GENERATED_BUILD_METADATA = Object.freeze({\n  appId: ${JSON.stringify("wording-lens")},\n  displayName: ${JSON.stringify("Wording Lens")},\n  version: ${JSON.stringify(packageData.version)},\n  updatedAt: ${JSON.stringify(updatedAt)},\n  source: ${JSON.stringify(source)},\n});\n`;
writeFileSync(resolve(root, "packages/core/src/generated-build-metadata.ts"), content, "utf8");
